import Foundation
import CryptoKit
import Testing
@testable import KMobile

struct ProvisioningSecurityTests {
    // Independent Python cryptography 50.0.2 vector: X25519, SHA256(PoP), shared AES-CTR cursor.
    // Synthetic fixed keys only; never used by the application.
    @Test func securityOneInteroperabilityVector() throws {
        let key = try Curve25519.KeyAgreement.PrivateKey(rawRepresentation: Data([0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f]))
        let security = ProvisioningSecurity(privateKey: key)
        #expect(security.hello() == Data([0x10, 0x01, 0x5a, 0x27, 0x08, 0x00, 0xa2, 0x01, 0x22, 0x0a, 0x20, 0x8f, 0x40, 0xc5, 0xad, 0xb6, 0x8f, 0x25, 0x62, 0x4a, 0xe5, 0xb2, 0x14, 0xea, 0x76, 0x7a, 0x6e, 0xc9, 0x4d, 0x82, 0x9d, 0x3d, 0x7b, 0x5e, 0x1a, 0xd1, 0xba, 0x6f, 0x3e, 0x21, 0x38, 0x28, 0x5f]))
        #expect(try security.proof(response: Data([0x10, 0x01, 0x5a, 0x39, 0x08, 0x01, 0xaa, 0x01, 0x34, 0x12, 0x20, 0x35, 0x80, 0x72, 0xd6, 0x36, 0x58, 0x80, 0xd1, 0xae, 0xea, 0x32, 0x9a, 0xdf, 0x91, 0x21, 0x38, 0x38, 0x51, 0xed, 0x21, 0xa2, 0x8e, 0x3b, 0x75, 0xe9, 0x65, 0xd0, 0xd2, 0xcd, 0x16, 0x62, 0x54, 0x1a, 0x10, 0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f]), code: "123456") == Data([0x10, 0x01, 0x5a, 0x27, 0x08, 0x02, 0xb2, 0x01, 0x22, 0x12, 0x20, 0xa8, 0xc5, 0xec, 0xd4, 0xb2, 0x2b, 0xe3, 0xdb, 0x5f, 0x97, 0x13, 0x45, 0x2a, 0xa5, 0x64, 0xa5, 0xb3, 0x8f, 0x4a, 0x65, 0x40, 0xdb, 0x36, 0x12, 0x0d, 0x25, 0x1e, 0xeb, 0x83, 0x54, 0xd2, 0xc1]))
        try security.verify(Data([0x10, 0x01, 0x5a, 0x27, 0x08, 0x03, 0xba, 0x01, 0x22, 0x1a, 0x20, 0xc2, 0xe7, 0x10, 0xae, 0xd1, 0x44, 0x40, 0xec, 0xa6, 0xd1, 0xe6, 0x21, 0xe9, 0x2f, 0x5f, 0x6f, 0x71, 0xac, 0xec, 0xa4, 0x77, 0x8e, 0xe0, 0x01, 0x0a, 0x3f, 0x67, 0x13, 0xca, 0x8f, 0x0d, 0x70]))
        #expect(security.authenticated)
        #expect(try security.exchange(Data("board request".utf8)) == Data([0x3b, 0xdf, 0xf2, 0xe1, 0x88, 0xf0, 0xe5, 0x33, 0xc3, 0x45, 0x11, 0xc9, 0x8a]))
        #expect(try security.exchange(Data([0xe7, 0x62, 0x70, 0xdf, 0x53, 0x49, 0x09, 0x53, 0x57, 0xa5, 0xf4])) == Data("board reply".utf8))
    }
    @Test func refusesUnauthenticatedPayload() {
        let security = ProvisioningSecurity()
        #expect(throws: AccessoryFailure.self) { try security.exchange(Data("secret".utf8)) }
    }
    @Test func rejectsSecurityDowngrade() {
        let security = ProvisioningSecurity()
        #expect(throws: AccessoryFailure.self) { try security.proof(response: Data([16, 0]), code: "123456") }
    }
}
